export function createStarterSampleDeck(targetUid: string = 'guest_user'): Deck {
  const entries: PortfolioCardEntry[] = STARTER_SAMPLE_CARDS.map((item) => ({
    id: `entry-${item.id}`,
    ownerId: targetUid,
    deckId: 'deck-sample-starter',
    cardId: item.card.id,
    card: item.card,
    condition: item.condition === 'DMG' ? 'Damaged' : item.condition,
    quantity: item.quantity,
    purchasePrice: item.purchasePrice,
    purchaseCurrency: 'USD',
    purchaseDate: '2026-07-15',
    isSold: false,
    gradingInfo: item.isGraded && item.gradingCompany
      ? {
          company: item.gradingCompany,
          grade: String(item.gradeScore || 10),
          certNumber: item.certNumber || '84920194',
          subgrades: item.subgrades,
        }
      : undefined,
  }));

  return {
    id: 'deck-sample-starter',
    ownerId: targetUid,
    name: 'Starter Binder & Slabs',
    description: 'Sample collection with verified market comps and PSA/BGS slab tracking.',
    colorHex: '#DC143C',
    isPublic: false,
    entries,
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}
